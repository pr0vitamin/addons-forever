#!/usr/bin/env bash
# Addons Forever sync.
#
# Builds the Bundle from every Module and installs the Host into the game's
# AddOns folder. Afterwards, type /reload in game.
#
# Usage: ./sync.sh [--config FILE] [--modules DIR]
#   --config FILE   local config to read (default: local.conf next to this script)
#   --modules DIR   folder holding Module folders (default: modules/ next to this script)
#
# Must run on bash 3.2 (macOS) as well as Git Bash on Windows.

set -euo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG="$ROOT/local.conf"
MODULES_DIR="$ROOT/modules"
HOST_DIR="$ROOT/host"
HOST_NAME="AddonsForever"

die() { printf 'sync: error: %s\n' "$*" >&2; exit 1; }
note() { printf 'sync: %s\n' "$*"; }

trim() {
  local s=$1
  s="${s#"${s%%[![:space:]]*}"}"
  s="${s%"${s##*[![:space:]]}"}"
  printf '%s' "$s"
}

# A Lua double-quoted string literal.
lua_quote() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '"%s"' "$s"
}

# The "=" padding for a Lua long bracket whose opening and closing forms do not
# occur in FILE. Always at least one "=": WoW's Lua 5.1 rejects any "[[" inside
# a level-0 "[[ ]]" string, which would stop the whole Bundle from loading.
long_level() {
  local file=$1 eq="="
  while grep -qF -e "]${eq}]" -e "[${eq}[" "$file"; do
    eq="${eq}="
  done
  printf '%s' "$eq"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --config) [ $# -ge 2 ] || die "--config needs a file"; CONFIG=$2; shift 2 ;;
    --modules) [ $# -ge 2 ] || die "--modules needs a folder"; MODULES_DIR=$2; shift 2 ;;
    -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1 (see --help)" ;;
  esac
done

# Config -----------------------------------------------------------------------

[ -f "$CONFIG" ] || die "no config found at $CONFIG. Copy local.conf.example to local.conf and set addons_path."

addons_path=$(sed -n 's/^[[:space:]]*addons_path[[:space:]]*=//p' "$CONFIG" | tr -d '\r' | tail -n 1)
addons_path=$(trim "$addons_path")
case "$addons_path" in
  \"*\"|\'*\') addons_path=${addons_path:1:${#addons_path}-2} ;;
esac
addons_path=${addons_path//\\//}
[ -n "$addons_path" ] || die "addons_path is not set in $CONFIG"
[ -d "$addons_path" ] || die "AddOns folder not found: $addons_path (check addons_path in $CONFIG)"

dest="$addons_path/$HOST_NAME"

# Build the Bundle ------------------------------------------------------------------
# Built before anything in the AddOns folder changes, so a failure leaves the
# previous install untouched.

tmp=$(mktemp "${TMPDIR:-/tmp}/addons-forever-bundle.XXXXXX")
trap 'rm -f "$tmp"' EXIT
count=0

{
  printf -- '-- Generated by sync.sh from your addons. Do not edit: it is overwritten on every sync.\n'

  if [ -d "$MODULES_DIR" ]; then
    for dir in "$MODULES_DIR"/*/; do
      [ -d "$dir" ] || continue
      dir=${dir%/}
      id=${dir##*/}
      toc="$dir/module.toc"
      if [ ! -f "$toc" ]; then
        note "skipping $id: it has no module.toc" >&2
        continue
      fi

      title=""
      files=()
      while IFS= read -r line || [ -n "$line" ]; do
        line=$(trim "${line%$'\r'}")
        case "$line" in
          "## Title:"*) title=$(trim "${line#"## Title:"}") ;;
          "#"*|"") ;;
          *) files+=("${line//\\//}") ;;
        esac
      done < "$toc"
      [ -n "$title" ] || title=$id

      printf '\n-- Module: %s\n' "$id"
      printf 'AddonsForever:_RegisterModule(%s, { title = %s }, {\n' "$(lua_quote "$id")" "$(lua_quote "$title")"
      if [ ${#files[@]} -gt 0 ]; then
        for f in "${files[@]}"; do
          src="$dir/$f"
          [ -f "$src" ] || die "addon $id lists $f in module.toc, but that file does not exist"
          eq=$(long_level "$src")
          printf '  { path = %s, code = [%s[\n' "$(lua_quote "modules/$id/$f")" "$eq"
          cat "$src"
          [ -z "$(tail -c 1 "$src")" ] || printf '\n'
          printf ']%s] },\n' "$eq"
        done
      fi
      printf '})\n'
      count=$((count + 1))
    done
  fi
} > "$tmp"

# Install the Host and Bundle -----------------------------------------------------

mkdir -p "$dest"
cp -R "$HOST_DIR"/. "$dest"/
cp "$tmp" "$dest/.Bundle.lua.new"
mv -f "$dest/.Bundle.lua.new" "$dest/Bundle.lua"

if [ "$count" -eq 0 ]; then
  note "no addons found in $MODULES_DIR; installed the Host with an empty Bundle."
else
  note "synced $count addon(s) into $dest"
fi
note "type /reload in game to load the changes."
